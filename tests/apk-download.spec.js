import { test, expect } from '@playwright/test';
import { createHash } from 'node:crypto';
import { readFile } from 'node:fs/promises';

test('home page downloads the exact signed Quest APK only after activating its visible link',async({page})=>{
  const requests=[],downloads=[];
  page.on('request',request=>{if(request.url().endsWith('.apk'))requests.push(request.url());});
  page.on('download',download=>downloads.push(download));
  await page.goto('./');
  const link=page.locator('#download-quest');
  await expect(link).toBeVisible();
  await expect(link).toHaveAccessibleName('Download Quest APK');
  await expect(link).toHaveAttribute('download','ImmersiveVideoPlayer-Quest.apk');
  await expect(page.locator('html')).toHaveAttribute('data-pretext','measured');
  await expect(link).toHaveAttribute('data-text-fit','single');
  expect(requests).toEqual([]);
  expect(downloads).toEqual([]);
  await link.focus();await expect(link).toBeFocused();
  const downloading=page.waitForEvent('download');
  await page.keyboard.press('Enter');
  const download=await downloading;
  expect(download.suggestedFilename()).toBe('ImmersiveVideoPlayer-Quest.apk');
  expect(await download.failure()).toBeNull();
  const bytes=await readFile(await download.path());
  expect(bytes.length).toBe(12768);
  expect(createHash('sha256').update(bytes).digest('hex')).toBe('af07861c7de91b344496e166bde18bd010fa863f620963fc1851d1819a2a7843');
  expect(downloads).toHaveLength(1);
  const address=new URL(download.url());
  expect(address.pathname).toMatch(/\/downloads\/ImmersiveVideoPlayer-Quest\.apk$/);
  expect(address.search).toBe('');expect(address.hash).toBe('');
  await expect(page.locator('#entry')).toBeVisible();
  await expect(page.locator('#player')).toBeHidden();
  await page.setViewportSize({width:320,height:560});
  await expect(link).toBeInViewport();
  await page.screenshot({path:test.info().outputPath('apk-download-320.png')});
  await page.setViewportSize({width:1280,height:720});
  await page.screenshot({path:test.info().outputPath('apk-download-desktop.png')});
  await page.setViewportSize({width:320,height:700});
  await page.addStyleTag({content:':root{font-size:32px} a{line-height:1.5;letter-spacing:.12em;word-spacing:.16em}'});
  await link.evaluate(el=>el.textContent='Quest-Installationsdatei herunterladen');
  await expect(link).toHaveAttribute('data-text-fit','wrapped');
  await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);
  expect(await link.evaluate(el=>el.scrollWidth<=el.clientWidth+2&&el.scrollHeight<=el.clientHeight+2&&parseFloat(getComputedStyle(el).fontSize)>=32)).toBe(true);
});
